/** @type {Record<string, EnergyFragment>} */
export const FRAGMENT_BY_ID = Object.fromEntries(ENERGY_FRAGMENTS.map((f) => [f.id, f]));

/** @param {string} id */
export function getFragment(id) {
  return FRAGMENT_BY_ID[id] || null;
}

/** @param {string} family */
export function fragmentsByFamily(family) {
  return ENERGY_FRAGMENTS.filter((f) => f.family === family);
}

/** @param {string} klass */
export function fragmentsByClass(klass) {
  return ENERGY_FRAGMENTS.filter((f) => f.class === klass);
}
