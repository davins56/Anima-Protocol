/**
 * @typedef {object} EnergyFragment
 * @property {string} id
 * @property {string} name
 * @property {number} libraryNo
 * @property {string} family
 * @property {FragmentClass} class
 * @property {FragmentElement} element
 * @property {FragmentTactic} tactic
 * @property {number | null} power
 * @property {number} mb
 * @property {string[]} codes
 * @property {string} description
 * @property {SummonKind} summon
 * @property {string} inspiredByFamily
 * @property {string} [summonNote]
 */

/**
 * @param {Omit<EnergyFragment, "libraryNo">[]} rows
 * @returns {EnergyFragment[]}
 */
function numberLibrary(rows) {
  return rows.map((row, i) => ({ ...row, libraryNo: i + 1 }));
}

