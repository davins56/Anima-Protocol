#!/usr/bin/env node
// Generates artifacts/anima-protocol/src/styles/anima-tokens.{css,ts} from design/anima-tokens.json.
// The same JSON was used to create the Figma variables (see docs/figma.md), so code and Figma stay 1:1.
// Usage: node scripts/design/sync-tokens.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const T = JSON.parse(readFileSync(resolve(root, "design/anima-tokens.json"), "utf8"));
const outDir = resolve(root, "artifacts/anima-protocol/src/styles");
const kebab = (n) => n.replace(/^color\//, "").replace(/\//g, "-");
const prim = (n) => `--anima-${n.replace(/\//g, "-")}`;

const css = [
  "/* GENERATED by scripts/design/sync-tokens.mjs from design/anima-tokens.json — do not edit. */",
  "/* Figma: Anima Protocol – Design System & Screens (VkJdHFwuUvVrNUiXwSgo82), collections Primitives / Anima · Semantic / Resonance / Layout. */",
  ":root {",
  ...Object.entries(T.primitives).map(([n, v]) => `  ${prim(n)}: ${v};`),
  ...Object.entries(T.semantic).map(([n, ref]) => `  --anima-${kebab(n)}: var(${prim(ref)});`),
  ...Object.entries(T.resonance).flatMap(([b, d]) => [
    `  --anima-resonance-${b}: var(${prim(d.color)});`,
    `  --anima-resonance-${b}-min: ${d.min};`,
    `  --anima-resonance-${b}-max: ${d.max};`,
  ]),
  `  --anima-resonance-spectrum: linear-gradient(90deg, ${spectrumStops().map(([p, h]) => `${h} ${(p * 100).toFixed(1)}%`).join(", ")});`,
  ...Object.entries(T.space).map(([n, v]) => `  --anima-${n.replace("/", "-")}: ${v}px;`),
  ...Object.entries(T.radius).map(([n, v]) => `  --anima-${n.replace("/", "-")}: ${v}px;`),
  ...Object.entries(T.effects).map(([n, e]) => `  --anima-${n.toLowerCase().replace("/", "-")}: 0 0 ${e.radius}px ${hexA(e.color, e.opacity)};`),
  "}",
  "",
].join("\n");

function hexA(h, a) {
  const v = h.replace("#", "");
  return `rgba(${parseInt(v.slice(0, 2), 16)}, ${parseInt(v.slice(2, 4), 16)}, ${parseInt(v.slice(4, 6), 16)}, ${a})`;
}
function spectrumStops() {
  const bands = Object.values(T.resonance);
  const stops = bands.map((b) => [(b.min + b.max) / 200, T.primitives[b.color]]);
  return [[0, stops[0][1]], ...stops, [1, stops[stops.length - 1][1]]];
}

const resolved = Object.fromEntries(Object.entries(T.semantic).map(([n, ref]) => [n, T.primitives[ref]]));
const ts = `/* GENERATED by scripts/design/sync-tokens.mjs from design/anima-tokens.json — do not edit. */
export const ANIMA_PRIMITIVES = ${JSON.stringify(T.primitives, null, 2)} as const;

/** Semantic tokens resolved to hex (Figma collection "Anima · Semantic", mode "Serenity Dark"). */
export const ANIMA_COLORS = ${JSON.stringify(resolved, null, 2)} as const;

export type ResonanceBandKey = ${Object.keys(T.resonance).map((k) => JSON.stringify(k)).join(" | ")};

/** Resonance spectrum along the W axis (0–100). Figma collection "Resonance". */
export const RESONANCE_SPECTRUM: ReadonlyArray<{ key: ResonanceBandKey; label: string; min: number; max: number; color: string; glyph: string }> = ${JSON.stringify(
  Object.entries(T.resonance).map(([key, b]) => ({ key, label: b.label, min: b.min, max: b.max, color: T.primitives[b.color], glyph: b.glyph })),
  null,
  2,
)};

/** Gradient stops (position 0–1, hex): band colour held at band centre, linear crossfade between centres. */
export const RESONANCE_STOPS: ReadonlyArray<readonly [number, string]> = ${JSON.stringify(spectrumStops())};

export const ANIMA_SPACE = ${JSON.stringify(Object.fromEntries(Object.entries(T.space).map(([k, v]) => [k.split("/")[1], v])))} as const;
export const ANIMA_RADIUS = ${JSON.stringify(Object.fromEntries(Object.entries(T.radius).map(([k, v]) => [k.split("/")[1], v])))} as const;
export const ANIMA_TYPE = ${JSON.stringify(T.type, null, 2)} as const;

const clamp = (f: number) => Math.min(100, Math.max(0, Number.isFinite(f) ? f : 0));

/** Band containing a W frequency (upper bound exclusive except at 100). */
export function resonanceBandAt(freq: number) {
  const f = clamp(freq);
  return RESONANCE_SPECTRUM.find((b) => f >= b.min && f < b.max) ?? RESONANCE_SPECTRUM[RESONANCE_SPECTRUM.length - 1];
}

function hexToRgb(h: string): [number, number, number] {
  const v = h.replace("#", "");
  return [parseInt(v.slice(0, 2), 16), parseInt(v.slice(2, 4), 16), parseInt(v.slice(4, 6), 16)];
}

/** Continuous (detent-free) spectrum colour at W, crossfading between band centres. Returns #rrggbb. */
export function spectrumColorAt(freq: number): string {
  const p = clamp(freq) / 100;
  for (let i = 1; i < RESONANCE_STOPS.length; i++) {
    const [p1, c1] = RESONANCE_STOPS[i];
    const [p0, c0] = RESONANCE_STOPS[i - 1];
    if (p <= p1) {
      const t = p1 === p0 ? 0 : (p - p0) / (p1 - p0);
      const a = hexToRgb(c0), b = hexToRgb(c1);
      return "#" + a.map((x, k) => Math.round(x + (b[k] - x) * t).toString(16).padStart(2, "0")).join("");
    }
  }
  return RESONANCE_STOPS[RESONANCE_STOPS.length - 1][1];
}

/** CSS linear-gradient for the full spectrum (same stops as Figma's FrequencyTuner ring). */
export const RESONANCE_GRADIENT_CSS = ${JSON.stringify(`linear-gradient(90deg, ${spectrumStops().map(([p, h]) => `${h} ${(p * 100).toFixed(1)}%`).join(", ")})`)};
`;

const check = process.argv.includes("--check");
const targets = [["anima-tokens.css", css], ["anima-tokens.ts", ts]];
let stale = false;
for (const [f, body] of targets) {
  const p = resolve(outDir, f);
  if (check) {
    let cur = "";
    try { cur = readFileSync(p, "utf8"); } catch {}
    if (cur !== body) { console.error(`stale: ${p}`); stale = true; }
  } else writeFileSync(p, body);
}
if (check && stale) process.exit(1);
console.log(check ? "anima tokens up to date" : `wrote ${targets.map((t) => t[0]).join(", ")}`);
