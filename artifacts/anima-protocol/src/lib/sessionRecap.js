// Session Recap: one normalized object drives both the modal and Export, so
// the downloaded file always carries exactly what the user sees.
//
// The server's generateSessionSummary returns `{ data: { summary,
// emotional_arc, key_moments, ... , generated } }` and animaClient.functions
// resolves `json.result`. Older code read fields that were never sent and
// filled the gaps with "A narrative journey unfolds..." / "Undefined"; there
// are no invented fallbacks here. A failed recap says so.

const asText = (value) => (typeof value === "string" ? value.trim() : "");

const asList = (value) =>
  Array.isArray(value)
    ? value.map((v) => (typeof v === "string" ? v.trim() : "")).filter(Boolean)
    : [];

/**
 * @param {any} result  what animaClient.functions.invoke("generateSessionSummary") resolved
 * @param {{ title?: string, messages?: unknown[] } | null} session
 * @param {Date} [now]
 */
export function normalizeSessionRecap(result, session, now = new Date()) {
  const data =
    result && typeof result === "object" && result.data && typeof result.data === "object"
      ? result.data
      : result && typeof result === "object"
        ? result
        : {};
  const summary = asText(data.summary);
  const generated = data.generated !== false && Boolean(summary);
  const sessionTitle = asText(session?.title);
  // The server counts only visible chat lines; trust it whenever it answered.
  const serverCount =
    typeof data.message_count === "number" ? data.message_count : Number.NaN;
  const messageCount =
    Number.isFinite(serverCount) && serverCount >= 0
      ? serverCount
      : Array.isArray(session?.messages)
        ? session.messages.length
        : 0;
  return {
    generated,
    error: generated
      ? ""
      : asText(data.error) || "The recap could not be generated. Please try again.",
    title: asText(data.title) || sessionTitle || "Session",
    date: now.toLocaleDateString("en-US", {
      weekday: "long",
      year: "numeric",
      month: "long",
      day: "numeric",
    }),
    time: now.toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit" }),
    messageCount,
    summary,
    keyMoments: asList(data.key_moments),
    characters: asList(data.characters_involved),
    emotionalArc: asText(data.emotional_arc),
    journalEntry: asText(data.journal_entry),
    reflections: asList(data.reflections),
  };
}

const RULE = "═══════════════════════════════════════════════════════════════";
const SUB = "───────────────────────────────────────────────────────────────";

function section(title, body) {
  return [SUB, title, SUB, body].join("\n");
}

/** Plain-text Export built from the same recap object the modal renders. */
export function buildSessionRecapExport(recap) {
  if (!recap) return "";
  const parts = [
    RULE,
    "                    SESSION JOURNAL RECAP",
    RULE,
    "",
    `Title: ${recap.title}`,
    `Date: ${recap.date} at ${recap.time}`,
    `Messages: ${recap.messageCount}`,
  ];
  if (recap.characters.length) parts.push(`Characters: ${recap.characters.join(", ")}`);
  parts.push("");
  if (!recap.generated) {
    parts.push(section("RECAP UNAVAILABLE", recap.error), "");
  } else {
    parts.push(section("SUMMARY", recap.summary), "");
    if (recap.keyMoments.length) {
      parts.push(
        section("KEY MOMENTS", recap.keyMoments.map((m, i) => `${i + 1}. ${m}`).join("\n")),
        "",
      );
    }
    if (recap.emotionalArc) parts.push(section("EMOTIONAL ARC", recap.emotionalArc), "");
    if (recap.journalEntry) parts.push(section("JOURNAL ENTRY", recap.journalEntry), "");
    if (recap.reflections.length) {
      parts.push(section("REFLECTIONS", recap.reflections.map((r) => `- ${r}`).join("\n")), "");
    }
  }
  parts.push(RULE, "Generated by Resonance.AI", RULE);
  return parts.join("\n");
}
